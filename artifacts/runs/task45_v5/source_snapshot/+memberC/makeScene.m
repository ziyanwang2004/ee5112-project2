function scene=makeScene(model,c,id)
data=memberC.scenarioData(id);
assert(isequal(c.qStart,data.qStart) && isequal(c.qGoal,data.qGoal),'Use caseOptions for this scenario.');
[T,~]=memberB.poeFK(model,(c.qStart+c.qGoal)/2);
b=find(strcmp(model.bodyNames,'wrist_1_link')); assert(isscalar(b));
p=T(1:3,4,b).';
% The first box fills the complete sub-table workspace up to world z=0.
boxes=data.boxes;
scene=struct('id',id,'anchor',p,'boxes',boxes,'qStart',c.qStart,'qGoal',c.qGoal, ...
    'description',data.description, ...
    'floorIndex',1,'tableHeight',0,'mountHeight',.20, ...
    'boxNames',{{'table_and_subtable_forbidden','central_rack','left_equipment','right_equipment','rear_guard'}}, ...
    'allowedWorldContactBody','mount_pedestal','allowedWorldContactObstacle',1, ...
    'mountPolicy','Only the fixed pedestal bottom may contact the table. No UR5 link or tool contact is allowed.');
end
