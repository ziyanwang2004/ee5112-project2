function s=summarizeRun(r,c)
v=r.acceptance;
s=struct('task',r.task,'scenario',r.scenarioId,'seed',r.seed,'mode',r.constraintMode, ...
    'success',r.success,'failures',{v.failures},'plannerSeconds',r.elapsedSeconds, ...
    'totalSeconds',r.totalSeconds,'iterations',size(r.history,1),'restarts',max(r.history(:,1)), ...
    'minVoxelClearance',v.minVoxelClearance,'minMeshClearance',v.mesh.minWorldSeparation, ...
    'maxOrientationDeg',v.maxOrientationDeg,'meanOrientationDeg',v.meanOrientationDeg, ...
    'jointPathLength',v.jointPathLength,'toolPathLength',v.toolPathLength,'smoothness',v.smoothness, ...
    'orientationWeight',c.orientationWeight,'noiseStd',c.noiseStd,'nWaypoints',c.nWaypoints, ...
    'nRollouts',c.nRollouts,'termination',r.termination,'denseStates',v.nStates, ...
    'sourceFingerprint',r.metadata.sourceFingerprint);
end
